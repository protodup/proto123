//! The central English string catalog (FR-027). Every user-visible string the engine
//! produces is a key here; `text` is the only place literals live.

/// Keys for user-visible text. Templates use `{pos}`, `{cols}`, and `{rows}` placeholders.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum StringKey {
    BadgeReady,
    BadgeValue,
    BadgeLabel,
    BadgeEdit,
    BadgePoint,
    BadgeMenu,
    BadgeDialog,
    DiagSyntax,
    DiagUseQuoteForText,
    DiagInvalidRange,
    DiagMoveOutOfGrid,
    DiagFontMetricsMismatch,
    StatusNothingToUndo,
    StatusNothingToRedo,
    StatusExt,
    PromptCopySource,
    PromptCopyDest,
    PromptMoveSource,
    PromptMoveDest,
    PromptConfirmNew,
    ButtonOk,
    ButtonCancel,
    ButtonYes,
    ButtonNo,
    MenuFile,
    MenuFileDesc,
    MenuFileNew,
    MenuFileNewDesc,
    MenuEdit,
    MenuEditDesc,
    MenuEditUndo,
    MenuEditUndoDesc,
    MenuEditRedo,
    MenuEditRedoDesc,
    MenuRange,
    MenuRangeDesc,
    MenuRangeErase,
    MenuRangeEraseDesc,
    MenuRangeCopy,
    MenuRangeCopyDesc,
    MenuRangeMove,
    MenuRangeMoveDesc,
    MenuView,
    MenuViewDesc,
    MenuViewTheme,
    MenuViewThemeDesc,
    AnnounceCellFormula,
    AnnounceCellValue,
    AnnounceCellLabel,
    AnnounceCellEmpty,
    AnnounceMenuRoot,
    AnnounceMenuSub,
    AnnounceWithStatus,
    EnlargeWindow,
}

pub fn text(key: StringKey) -> &'static str {
    match key {
        StringKey::BadgeReady => "READY",
        StringKey::BadgeValue => "VALUE",
        StringKey::BadgeLabel => "LABEL",
        StringKey::BadgeEdit => "EDIT",
        StringKey::BadgePoint => "POINT",
        StringKey::BadgeMenu => "MENU",
        StringKey::BadgeDialog => "DIALOG",
        StringKey::DiagSyntax => {
            "Formula syntax error at character {pos}; the entry was not stored"
        }
        StringKey::DiagUseQuoteForText => {
            "To store text that starts with a digit, begin it with an apostrophe (')"
        }
        StringKey::DiagInvalidRange => "Enter a valid cell or range reference (for example A1:B3)",
        StringKey::DiagMoveOutOfGrid => "Move destination extends outside the grid",
        StringKey::DiagFontMetricsMismatch => {
            "Canvas font metrics differ from theme tokens; pointer mapping adjusted"
        }
        StringKey::StatusNothingToUndo => "Nothing to undo",
        StringKey::StatusNothingToRedo => "Nothing to redo",
        StringKey::StatusExt => "[EXT]",
        StringKey::PromptCopySource => "Copy source range:",
        StringKey::PromptCopyDest => "Copy destination range:",
        StringKey::PromptMoveSource => "Move source range:",
        StringKey::PromptMoveDest => "Move destination range:",
        StringKey::PromptConfirmNew => "Discard current workbook and start a new one?",
        StringKey::ButtonOk => "OK",
        StringKey::ButtonCancel => "Cancel",
        StringKey::ButtonYes => "Yes",
        StringKey::ButtonNo => "No",
        StringKey::MenuFile => "File",
        StringKey::MenuFileDesc => "Workbook commands",
        StringKey::MenuFileNew => "New",
        StringKey::MenuFileNewDesc => "Start a new empty workbook",
        StringKey::MenuEdit => "Edit",
        StringKey::MenuEditDesc => "Undo and redo changes",
        StringKey::MenuEditUndo => "Undo",
        StringKey::MenuEditUndoDesc => "Undo the last change",
        StringKey::MenuEditRedo => "Redo",
        StringKey::MenuEditRedoDesc => "Redo the last undone change",
        StringKey::MenuRange => "Range",
        StringKey::MenuRangeDesc => "Erase, copy, or move cells",
        StringKey::MenuRangeErase => "Erase",
        StringKey::MenuRangeEraseDesc => "Clear the selected cells",
        StringKey::MenuRangeCopy => "Copy",
        StringKey::MenuRangeCopyDesc => "Copy a range to another place",
        StringKey::MenuRangeMove => "Move",
        StringKey::MenuRangeMoveDesc => "Move a range to another place",
        StringKey::MenuView => "View",
        StringKey::MenuViewDesc => "Display and theme settings",
        StringKey::MenuViewTheme => "Theme",
        StringKey::MenuViewThemeDesc => "Cycle through built-in color themes",
        StringKey::AnnounceCellFormula => "{addr}, formula {formula}, value {value}, {mode}",
        StringKey::AnnounceCellValue => "{addr}, value {value}, {mode}",
        StringKey::AnnounceCellLabel => "{addr}, label {label}, {mode}",
        StringKey::AnnounceCellEmpty => "{addr}, empty, {mode}",
        StringKey::AnnounceMenuRoot => "Menu {item}: {desc}, {mode}",
        StringKey::AnnounceMenuSub => "Menu {parent}, {item}: {desc}, {mode}",
        StringKey::AnnounceWithStatus => "{base}, {status}",
        StringKey::EnlargeWindow => "Enlarge the window to at least {cols}x{rows}",
    }
}
